#!/usr/bin/env python3
"""Generate Go/Kotlin command inventories from shell-commands.json.

Only data is generated; language types and parser/help behavior stay handwritten.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Literal, TypedDict, cast

ROOT = Path(__file__).resolve().parent.parent
GO_OUTPUT = ROOT / "controller/internal/command/shell_contract_generated.go"
KOTLIN_OUTPUT = ROOT / "agent/src/main/java/io/dropcheck/agent/AgentShellContract.kt"
HEADER = "// Code generated by tools/generate_shell_contract.py; DO NOT EDIT."
LIST_FIELDS: tuple[
    Literal["positionals", "required", "switches", "values", "pc_values"], ...
] = ("positionals", "required", "switches", "values", "pc_values")
EFFECTS = {"local", "read", "probe", "mutation", "session"}
# Kotlin interpolates '$' and, unlike JSON/Go, has no '\f' string escape.
KOTLIN_ESCAPES = str.maketrans(
    {
        "\\": r"\\",
        '"': r"\"",
        "$": r"\$",
        **{chr(code): f"\\u{code:04x}" for code in (*range(32), 0x2028, 0x2029)},
    }
)


class Command(TypedDict):
    """Normalized command metadata; pc_values extend only the Go inventory."""

    path: str
    effect: str
    description: str
    positionals: list[str]
    required: list[str]
    switches: list[str]
    values: list[str]
    pc_values: list[str]
    enums: dict[str, list[str]]


class ShellDefinition(TypedDict):
    """Portable commands and shared enum choices, preserving source order."""

    value_sets: dict[str, list[str]]
    commands: list[Command]


def _unique_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    """Reject duplicate JSON properties instead of silently keeping the last."""
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON property {key!r}")
        result[key] = value
    return result


def _object(value: object, label: str) -> dict[str, object]:
    """Require a JSON object at the named input boundary."""
    if not isinstance(value, dict):
        raise ValueError(f"{label}: expected an object")
    return cast(dict[str, object], value)


def _text(value: object, label: str) -> str:
    """Require nonempty text that can be written to UTF-8 source files."""
    if not isinstance(value, str) or not value:
        raise ValueError(f"{label}: expected a nonempty string")
    value.encode("utf-8")
    return value


def _strings(value: object, label: str) -> list[str]:
    """Validate an ordered string list without coercion or duplicates."""
    if not isinstance(value, list):
        raise ValueError(f"{label}: expected a string list")
    items = [_text(item, label) for item in value]
    if len(items) != len(set(items)):
        raise ValueError(f"{label}: duplicate values")
    return items


def _enum_map(value: object, label: str) -> dict[str, list[str]]:
    """Validate named, nonempty enum choices."""
    choices: dict[str, list[str]] = {}
    for key, values in _object(value, label).items():
        name = _text(key, label)
        choices[name] = _strings(values, f"{label}.{name}")
        if not choices[name]:
            raise ValueError(f"{label}.{name}: enum choices must not be empty")
    return choices


def load_definition(path: Path) -> ShellDefinition:
    """Validate the complete definition before either output can be written."""
    raw = _object(
        json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object),
        str(path),
    )
    if raw.keys() != {"value_sets", "commands"}:
        raise ValueError("definition must contain only value_sets and commands")
    rows = raw["commands"]
    if not isinstance(rows, list) or not rows:
        raise ValueError("commands: expected a nonempty list")
    definition: ShellDefinition = {
        "value_sets": _enum_map(raw["value_sets"], "value_sets"),
        "commands": [],
    }
    seen: set[str] = set()
    for index, value in enumerate(rows):
        label = f"commands[{index}]"
        row = _object(value, label)
        unknown = row.keys() - Command.__annotations__.keys()
        if unknown:
            raise ValueError(f"{label}: unknown fields {', '.join(sorted(unknown))}")
        lists = {
            key: _strings(row.get(key, []), f"{label}.{key}") for key in LIST_FIELDS
        }
        command: Command = {
            "path": _text(row.get("path"), f"{label}.path"),
            "effect": _text(row.get("effect"), f"{label}.effect"),
            "description": _text(row.get("description"), f"{label}.description"),
            "positionals": lists["positionals"],
            "required": lists["required"],
            "switches": lists["switches"],
            "values": lists["values"],
            "pc_values": lists["pc_values"],
            "enums": _enum_map(row.get("enums", {}), f"{label}.enums"),
        }
        if command["path"] in seen:
            raise ValueError(f"{label}: duplicate path {command['path']!r}")
        seen.add(command["path"])
        if command["effect"] not in EFFECTS:
            raise ValueError(f"{label}: unknown effect {command['effect']!r}")
        if not set(command["required"]) <= set(command["values"]):
            raise ValueError(f"{label}: required arguments must be value options")
        if set(command["switches"]) & set(command["values"] + command["pc_values"]):
            raise ValueError(f"{label}: switches overlap value options")
        if set(command["pc_values"]) & set(command["values"]):
            raise ValueError(f"{label}: pc_values duplicate portable options")
        if not command["enums"].keys() <= set(command["values"]):
            raise ValueError(f"{label}: enum overrides must name value options")
        definition["commands"].append(command)
    return definition


def go_string(value: str) -> str:
    """Quote UTF-8 text as a Go interpreted string literal."""
    return json.dumps(value, ensure_ascii=False)


def kotlin_string(value: str) -> str:
    """Quote text as a literal Kotlin string, never a string template."""
    return '"' + value.translate(KOTLIN_ESCAPES) + '"'


def _enums_for(definition: ShellDefinition, command: Command) -> dict[str, list[str]]:
    """Apply per-command overrides only to that command's portable value options."""
    choices = definition["value_sets"] | command["enums"]
    return {key: values for key, values in choices.items() if key in command["values"]}


def render_go(definition: ShellDefinition) -> str:
    """Render the Go inventory, including host-only options, and run gofmt."""
    lines = [HEADER, "package command", "", "var portableGrammar = []Grammar{"]
    for command in definition["commands"]:
        fields = ["Path: " + go_string(command["path"])]
        for key in LIST_FIELDS[:-1]:
            values = command[key] + (command["pc_values"] if key == "values" else [])
            if values:
                items = ", ".join(map(go_string, values))
                fields.append(f"{key.title()}: []string{{{items}}}")
        fields.extend(
            (
                "Effect: " + go_string(command["effect"]),
                "Description: " + go_string(command["description"]),
            )
        )
        enums = _enums_for(definition, command)
        if enums:
            entries = (
                go_string(key) + ": {" + ", ".join(map(go_string, values)) + "}"
                for key, values in enums.items()
            )
            fields.append("Enums: map[string][]string{" + ", ".join(entries) + "}")
        lines.append("    {" + ", ".join(fields) + "},")
    lines.append("}")
    return subprocess.run(
        ["gofmt"],
        input="\n".join(lines) + "\n",
        encoding="utf-8",
        stdout=subprocess.PIPE,
        check=True,
    ).stdout


def render_kotlin(definition: ShellDefinition) -> str:
    """Render portable Kotlin inventory data without generating types or behavior."""
    lines = [
        HEADER,
        "package io.dropcheck.agent",
        "",
        "internal object AgentShellContract {",
        "    val rows = listOf(",
    ]
    for command in definition["commands"]:
        fields = [kotlin_string(command["path"])]
        for key in LIST_FIELDS[:-1]:
            if values := command[key]:
                items = ", ".join(map(kotlin_string, values))
                fields.append(f"{key} = listOf({items})")
        fields.extend(
            (
                "effect = " + kotlin_string(command["effect"]),
                "description = " + kotlin_string(command["description"]),
            )
        )
        enums = _enums_for(definition, command)
        if enums:
            entries = []
            for key, values in enums.items():
                items = ", ".join(map(kotlin_string, values))
                entries.append(f"{kotlin_string(key)} to listOf({items})")
            fields.append("enums = mapOf(" + ", ".join(entries) + ")")
        lines.append("        AgentShellSyntax(" + ", ".join(fields) + "),")
    return "\n".join(lines + ["    )", "}", ""])


def main() -> None:
    """Generate both inventories, or check drift without modifying files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if committed inventories differ"
    )
    args = parser.parse_args()
    try:
        definition = load_definition(ROOT / "shell-commands.json")
        outputs = {
            GO_OUTPUT: render_go(definition),
            KOTLIN_OUTPUT: render_kotlin(definition),
        }
        for path, content in outputs.items():
            if args.check:
                if not path.is_file() or path.read_text(encoding="utf-8") != content:
                    parser.exit(
                        1,
                        f"Out of date: {path.relative_to(ROOT)}; "
                        "run make generate-shell\n",
                    )
            else:
                path.write_text(content, encoding="utf-8")
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"generate-shell: {error}\n")


if __name__ == "__main__":
    main()
