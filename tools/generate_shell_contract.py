#!/usr/bin/env python3
"""Generate the two language bindings for the portable interactive command inventory."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def outputs():
    contract = json.loads((ROOT / "shell/commands.json").read_text())
    rows = contract["commands"]
    paths = [row["path"] for row in rows]
    assert len(paths) == len(set(paths)), "duplicate command path"
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    go = ['// Code generated by tools/generate_shell_contract.py; DO NOT EDIT.', 'package command', '', 'var portableGrammar = []Grammar{']
    kotlin = ['// Code generated by tools/generate_shell_contract.py; DO NOT EDIT.', 'package io.dropcheck.agent', '',
              'internal data class AgentShellSyntax(', '    val path: String,', '    val positionals: List<String> = emptyList(),',
              '    val required: List<String> = emptyList(),', '    val switches: List<String> = emptyList(),', '    val values: List<String> = emptyList(),',
              '    val enums: Map<String, List<String>> = emptyMap(),',
              '    val effect: String,', '    val description: String,', ') {', "    val parts = path.split(' ')",
              '    val keys get() = switches + values', '    val position get() = positionals.joinToString(" ") { it.uppercase() }',
              '    fun usage(): String = (listOf(path) + positionals.map { "<${it.uppercase()}>" } + required.map { "$it <value>" } +',
              '        switches.map { "[$it]" } + values.filterNot { it in required }.map { "[$it <value>]" }).joinToString(" ")',
              '}', '', 'internal object AgentShellContract {', '    val rows = listOf(']
    for row in rows:
        assert set(row) <= {'path', 'effect', 'description', 'positionals', 'required', 'switches', 'values', 'pc_values', 'enums'}, 'unknown command property'
        assert row['effect'] in ('local', 'read', 'probe', 'mutation', 'session')
        for field in ('positionals', 'required', 'switches', 'values', 'pc_values'):
            values = row.get(field, [])
            assert len(values) == len(set(values)), (row['path'], field)
        assert set(row.get('required', [])) <= set(row.get('values', []))
        assert not set(row.get('switches', [])) & set(row.get('values', []))
        gfields = ['Path: ' + quote(row['path'])]
        kfields = [quote(row['path'])]
        for field in ('positionals', 'required', 'switches', 'values'):
            values = row.get(field, [])
            go_values = values + (row.get('pc_values', []) if field == 'values' else [])
            if go_values:
                gfields.append(field.title() + ': []string{' + ', '.join(map(quote, go_values)) + '}')
            if values:
                kfields.append(field + ' = listOf(' + ', '.join(map(quote, values)) + ')')
        for field in ('effect', 'description'):
            gfields.append(field.title() + ': ' + quote(row[field]))
            kfields.append(field + ' = ' + quote(row[field]))
        enums = {key: values for key, values in (contract['value_sets'] | row.get('enums', {})).items() if key in row.get('values', [])}
        if enums:
            gfields.append('Enums: map[string][]string{' + ', '.join(quote(key) + ': {' + ', '.join(map(quote, values)) + '}' for key, values in enums.items()) + '}')
            kfields.append('enums = mapOf(' + ', '.join(quote(key) + ' to listOf(' + ', '.join(map(quote, values)) + ')' for key, values in enums.items()) + ')')
        go.append('    {' + ', '.join(gfields) + '},')
        kotlin.append('        AgentShellSyntax(' + ', '.join(kfields) + '),')
    go += ['}']
    kotlin += ['    )', '}']
    go_text = subprocess.run(['gofmt'], input='\n'.join(go) + '\n', text=True, capture_output=True, check=True).stdout
    return {
        ROOT / 'controller/internal/command/shell_contract_generated.go': go_text,
        ROOT / 'agent/src/main/java/io/dropcheck/agent/AgentShellContract.kt': '\n'.join(kotlin) + '\n',
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Out of date: {path.relative_to(ROOT)}; run make generate-shell')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
